/** The participants a flow touches, in a fixed left-to-right order. */
export function nodesFor(flow) {
  const order = ['ui', 'api', 'threads', 'sub', 'redis', 'pg'];
  const used = new Set(flow.flatMap(([from, to]) => [from, to]));
  return order.filter((id) => used.has(id));
}
